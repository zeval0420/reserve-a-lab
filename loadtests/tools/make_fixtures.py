"""Generate sql/fixtures.sql: synthetic accounts and inventory for the load tests.

Everything created here lives only in the test window: the database is restored
from the pre-test mysqldump afterwards. No real account is used or modified,
except that every real e-mail address is rewritten to @example.invalid as a
second guard (outbound SMTP is also blocked by a firewall rule).

The shared password for the synthetic accounts is generated once and kept in
loadtests/.env (gitignored); the k6 scripts read it from there.

Usage: python -I tools/make_fixtures.py
"""
import hashlib
import pathlib
import secrets

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"
OUT = ROOT / "sql" / "fixtures.sql"

N_TEACHERS = 500
N_ADMINS = 5


def load_password():
    if ENV.exists():
        for line in ENV.read_text().splitlines():
            if line.startswith("LT_PASSWORD="):
                return line.split("=", 1)[1].strip()
    pw = secrets.token_urlsafe(18)
    ENV.write_text(f"LT_PASSWORD={pw}\n")
    return pw


def main():
    pw = load_password()
    md5 = hashlib.md5(pw.encode()).hexdigest()  # the application stores MD5 hashes
    rows = []
    for i in range(1, N_TEACHERS + 1):
        rows.append(f"('LT-T{i:04d}','lt.t{i:04d}','Load','T{i:04d}','Tester','{md5}','SST-I','lt.t{i:04d}@example.invalid','faculty','active')")
    for i in range(1, N_ADMINS + 1):
        rows.append(f"('LT-A{i:02d}','lt.a{i:02d}','Load','A{i:02d}','Admin','{md5}','Sci. Res. Assist.','lt.a{i:02d}@example.invalid','staff','active')")

    items = []
    for i in range(1, 11):
        items.append(f"('LT-C{i:02d}','LT Consumable {i:02d}','Consumable','Science Laboratory 1','Science Laboratory 1',1000000,'piece','loadtest','Available',NULL,0)")
    # Item for the "last few units" concurrency test (quantity reset before every repetition)
    items.append("('LT-LAST','LT Last Units','Consumable','Science Laboratory 1','Science Laboratory 1',5,'piece','loadtest','Available',NULL,0)")
    # Item for the manual-deduction control test (transactional endpoint)
    items.append("('LT-MANUAL','LT Manual Deduct','Consumable','Science Laboratory 1','Science Laboratory 1',5,'piece','loadtest','Available',NULL,0)")

    sql = f"""-- Generated by tools/make_fixtures.py. Load-test fixtures; removed by the post-test restore.
SET NAMES latin1;

-- Second guard against outgoing mail: no real address remains in the database.
UPDATE accounts SET email = CONCAT('real.', REPLACE(employeeID, ' ', ''), '@example.invalid');
UPDATE student_directory SET studentEmail = CONCAT('student.', LRN, '@example.invalid');

DELETE FROM accounts WHERE employeeID LIKE 'LT-%';
INSERT INTO accounts (employeeID, username, firstname, middlename, lastname, password, position, email, type, status) VALUES
{(","+chr(10)).join(rows)};

DELETE FROM scilab_inventory WHERE productID LIKE 'LT-%';
INSERT INTO scilab_inventory (productID, item, classification, location, laboratory, quantity, unit, description, status, threshold_qty, threshold_notified) VALUES
{(","+chr(10)).join(items)};

-- Table expected by ajax_inventory.php (deduct_inventory). Its migration,
-- sql/inventory_deductions.sql, was removed from the repo in commit 8f9d971 and
-- never applied locally; created here from that file for the control test.
CREATE TABLE IF NOT EXISTS `scilab_inventory_deductions` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `batch_id` varchar(36) NOT NULL,
  `inventory_id` int(11) NOT NULL,
  `item` varchar(255) NOT NULL,
  `description` varchar(255) NOT NULL DEFAULT '',
  `classification` varchar(20) NOT NULL,
  `quantity_deducted` int(6) NOT NULL,
  `quantity_before` int(6) NOT NULL,
  `quantity_after` int(6) NOT NULL,
  `reason` varchar(255) NOT NULL,
  `deducted_by` varchar(100) NOT NULL DEFAULT '',
  `deducted_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_inventory_id` (`inventory_id`),
  KEY `idx_batch_id` (`batch_id`),
  KEY `idx_deducted_at` (`deducted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci;
"""
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(sql, encoding="latin-1")
    print(f"wrote {OUT} ({N_TEACHERS} teachers, {N_ADMINS} admins, {len(items)} items)")


if __name__ == "__main__":
    main()
